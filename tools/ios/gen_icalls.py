#!/usr/bin/env python3
"""Generate RegisterAllStrippedInternalCalls() for an IL2CPP player.

Unity's prebuilt iOS engine library leaves every RegisterModuleICalls_<Module>() empty: the
editor generates RegisterAllStrippedInternalCalls(), calling one Register_<Class>_<Method>()
per engine binding the managed code uses. Without it every UnityEngine internal call throws
MissingMethodException.

usage: gen_icalls.py <Il2CppOutput dir> <libiPhone-lib-il2cpp.a> <out.cpp>"""
import glob, os, re, subprocess, sys


def available(lib):
    out = subprocess.run(["nm", "-arch", "arm64", "-g", lib], capture_output=True, text=True).stdout
    regs = set()
    for line in out.splitlines():
        parts = line.split()
        if len(parts) != 3 or parts[1] != "T":
            continue
        m = re.match(r"__Z(\d+)(Register_\w+)$", parts[2])
        if m and m.group(2)[int(m.group(1)):] == "v":       # void Register_X()
            regs.add(m.group(2)[:int(m.group(1))])
    return regs


def used(il):
    names = set()
    rx = re.compile(r'il2cpp_codegen_resolve_icall \("([^"]*)"\)')
    for f in glob.glob(os.path.join(il, "*.cpp")):
        with open(f, errors="replace") as fh:
            names.update(rx.findall(fh.read()))
    return names


def main(il, lib, out):
    regs = available(lib)
    want, missing = set(), []
    for ic in sorted(used(il)):
        if ic.startswith(("System.", "Mono.")):          # class library: registered by libil2cpp
            continue
        fn = "Register_" + re.sub(r"[.:/+`<>]+", "_", ic.split("(")[0])
        (want.add(fn) if fn in regs else missing.append(ic))
    fns = sorted(want)
    with open(out + ".tmp", "w") as fh:
        fh.write("// generated by tools/ios/gen_icalls.py\n")
        fh.writelines("void %s();\n" % f for f in fns)
        fh.write("\nvoid RegisterAllStrippedInternalCalls()\n{\n")
        fh.writelines("    %s();\n" % f for f in fns)
        fh.write("}\n")
    os.replace(out + ".tmp", out)
    print("icalls: %d registered, %d without a binding" % (len(fns), len(missing)))
    for ic in missing:
        print("  no binding:", ic)


if __name__ == "__main__":
    main(*sys.argv[1:4])
